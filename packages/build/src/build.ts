import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { platformLabel } from '@deckbuilderkit/server-core';
import { type AppDir, run } from './app.ts';
import { writeIco } from './icon.ts';
import { PUBLIC_KEY_FILE } from './keys.ts';

const TARGETS = ['windows-x64', 'linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64'] as const;
export type Target = (typeof TARGETS)[number];

/** `--target` value → targets; none means this machine. */
export function parseTargets(value: string | undefined): Target[] {
  if (!value) {
    const os = process.platform === 'win32' ? 'windows' : process.platform;
    return [`${os}-${process.arch}` as Target];
  }
  if (value === 'all') return [...TARGETS];
  const list = value.split(',').map((t) => t.trim());
  for (const t of list) if (!(TARGETS as readonly string[]).includes(t)) throw new Error(`unknown target ${t}; use ${TARGETS.join(', ')}`);
  return list as Target[];
}

/** A file-name-safe form of an app name (the update manifest only accepts `[\w.-]`); `fallback` when nothing usable is left. */
export function fileSlug(name: string, fallback = 'app'): string {
  const slug = name
    .replace(/\s+/g, '-')
    .replace(/[^\w.-]/g, '')
    .replace(/([.-])\1+/g, '$1');
  return !slug || slug.startsWith('.') ? fallback : slug;
}

/** `<slug>-<version>-`: what every release file name of the app starts with. */
export function releasePrefix(app: AppDir): string {
  return `${fileSlug(app.name, app.id)}-${app.version}-`;
}

export function buildWeb(app: AppDir): void {
  run(app, ['bun', 'x', 'vite', 'build', '--logLevel', 'warn']);
}

function filesUnder(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => relative(dir, join(e.parentPath, e.name)).replaceAll('\\', '/'))
    .sort();
}

/**
 * Writes the exe's entrypoints to `.build/`: `entry.ts` imports every file of dist/web
 * `with { type: 'file' }` so `bun build --compile` puts them in the exe, registers them, then
 * runs server/main.ts; `window-worker.ts` is the native window worker, `archive-worker.ts` the 7z worker.
 */
function writeEntries(app: AppDir): string {
  const out = join(app.dir, '.build');
  const webDist = join(app.dir, 'dist/web');
  const files = filesUnder(webDist);
  if (!files.includes('index.html')) throw new Error('dist/web/index.html missing; run build:web');
  mkdirSync(out, { recursive: true });

  const keyFile = join(app.dir, PUBLIC_KEY_FILE);
  const key = existsSync(keyFile) ? readFileSync(keyFile, 'utf8').trim() : '';
  const imports = files.map((path, i) => `import f${i} from ${JSON.stringify(`../dist/web/${path}`)} with { type: 'file' };`);
  const map = files.map((path, i) => `  ${JSON.stringify(path)}: f${i},`);
  writeFileSync(
    join(out, 'assets.ts'),
    [
      '// Generated by `deckbuilder build`; do not edit.',
      `import { setEmbeddedWebAssets${key ? ', setEmbeddedUpdateKey' : ''} } from '@deckbuilderkit/server-core';`,
      ...imports,
      `setEmbeddedWebAssets({\n${map.join('\n')}\n});`,
      // The updater then trusts only manifests signed with this key (`deckbuilder keygen`).
      ...(key ? [`setEmbeddedUpdateKey(${JSON.stringify(key)});`] : []),
      '',
    ].join('\n'),
  );
  // ES modules run in import order: the assets are registered before main.ts calls runApp.
  writeFileSync(
    join(out, 'entry.ts'),
    "// Generated by `deckbuilder build`; do not edit.\nimport './assets.ts';\nimport '../server/main.ts';\n",
  );
  // Inside the exe, the shell's `new URL('./window-worker.ts', import.meta.url)` resolves next to
  // the bundled entry, so the worker entrypoint must sit beside entry.ts.
  writeFileSync(
    join(out, 'window-worker.ts'),
    "// Generated by `deckbuilder build`; do not edit.\nimport '@deckbuilderkit/shell/window-worker';\n",
  );
  // Same for server-mods' 7z worker (archive extract/compress).
  writeFileSync(
    join(out, 'archive-worker.ts'),
    "// Generated by `deckbuilder build`; do not edit.\nimport '@deckbuilderkit/server-mods/archive-worker';\n",
  );
  return out;
}

/** Compiles one self-contained exe for `target` into release/ and returns its path. */
export async function buildExe(app: AppDir, target: Target): Promise<string> {
  const dir = writeEntries(app);
  const [os, arch] = target.split('-') as [string, string];
  const windows = os === 'windows';
  const out = join(app.dir, 'release', `${releasePrefix(app)}${platformLabel(os, arch)}${windows ? '.exe' : ''}`);
  try {
    rmSync(out, { force: true });
  } catch (err) {
    // Windows locks a running exe; Bun reports that as EFAULT or EBUSY.
    throw new Error(`Can't replace ${relative(app.dir, out)}: quit the running app first. (${(err as Error).message})`);
  }

  const cmd = ['bun', 'build', join(dir, 'entry.ts'), join(dir, 'window-worker.ts'), join(dir, 'archive-worker.ts'), '--compile', '--minify', `--target=bun-${target}`, `--outfile=${out}`];
  if (windows) {
    const ico = join(app.dir, '.build', 'icon.ico');
    await writeIco(join(app.dir, 'web/public/favicon.svg'), ico);
    cmd.push(
      '--windows-hide-console',
      `--windows-icon=${ico}`,
      `--windows-title=${app.name}`,
      `--windows-description=${app.name}`,
      `--windows-version=${app.version.split('-')[0]}.0`,
    );
  }
  run(app, cmd);
  console.log(`built ${relative(app.dir, out)}`);
  return out;
}
